SELECT        Продажи.*, Покупатели.Номер_телефона, Покупатели.Адрес, Товары.[Наименование товара], Товары.Цена, Товары.Описание
FROM            Покупатели INNER JOIN
                         Продажи ON Покупатели.Покупатель = Продажи.Покупатель INNER JOIN
                         Товары ON Продажи.Код_товара = Товары.[Код товара]