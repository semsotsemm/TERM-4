CREATE TABLE TIMETABLE
(
    IDGROUP int NOT NULL FOREIGN KEY REFERENCES GROUPS(IDGROUP),
    AUDITORIUM char(20) NOT NULL FOREIGN KEY REFERENCES AUDITORIUM(AUDITORIUM),
    SUBJECT char(10) NOT NULL FOREIGN KEY REFERENCES SUBJECT(SUBJECT),
    TEACHER char(20) NOT NULL FOREIGN KEY REFERENCES TEACHER(TEACHER),
    DAY_OF_WEEK tinyint CHECK (DAY_OF_WEEK BETWEEN 1 AND 6), 
    LESSON_TIME tinyint CHECK (LESSON_TIME BETWEEN 1 AND 8), 
    CONSTRAINT PK_TIMETABLE PRIMARY KEY (DAY_OF_WEEK, LESSON_TIME, AUDITORIUM)
);

